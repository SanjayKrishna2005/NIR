/* =============================================================================
 * Pipeline driver functions
 * ============================================================================= */

/* Write one 16-bit sample to in_bram at word-aligned offset */
static void bram_write_sample(u32 base, u32 idx, u16 val)
{
    /* AXI BRAM Controller uses 32-bit aligned access */
    Xil_Out32(base + idx * 4, (u32)val);
}

/* Read one byte from out_bram at word-aligned offset, sign-extend */
static s8 bram_read_feature(u32 base, u32 idx)
{
    u32 raw = Xil_In32(base + idx * 4) & 0xFF;
    return (s8)(raw > 127 ? raw - 256 : raw);
}

/* Write 224 raw ADC samples to in_bram */
static void write_spectrum(const u16 *samples)
{
    u32 i;
    for (i = 0; i < N_CHANNELS; i++)
        bram_write_sample(IN_BRAM_BASE, i, samples[i]);
}

/* Assert ctrl_start via AXI GPIO Channel 1 */
static void pulse_start(void)
{
    Xil_Out32(GPIO_BASE + GPIO_DATA, 0x00000001U);
}

/* Deassert ctrl_start */
static void clear_start(void)
{
    Xil_Out32(GPIO_BASE + GPIO_DATA, 0x00000000U);
}

/* Poll ctrl_done via AXI GPIO Channel 2, returns 1 on success, 0 on timeout */
static int poll_done(void)
{
    u32 timeout = TIMEOUT_CYCLES;
    while (timeout--) {
        if (Xil_In32(GPIO_BASE + GPIO2_DATA) & 0x1U)
            return 1;
    }
    return 0;
}

/* Read 224 INT8 features from out_bram */
static void read_features(s8 *feats)
{
    u32 i;
    for (i = 0; i < N_CHANNELS; i++)
        feats[i] = bram_read_feature(OUT_BRAM_BASE, i);
}

/* Full pipeline: write → start → poll → read → clear */
static int run_pipeline(const u16 *samples, s8 *feats)
{
    write_spectrum(samples);
    pulse_start();
    if (!poll_done()) {
        clear_start();
        return -1; /* timeout */
    }
    read_features(feats);
    clear_start();
    return 0;
}

/* =============================================================================
 * Q15 LinearSVC inference
 * score[c] = dot(W[c], x) + b[c]  in int32
 * Returns 1-indexed class_id (1..5)
 * ============================================================================= */
static int svm_predict(const s8 *feats)
{
    int best_class = 1;
    s32 best_score = -2147483647;
    int c, i;

    for (c = 0; c < N_CLASSES; c++) {
        s32 score = SVM_B[c];
        for (i = 0; i < N_CHANNELS; i++)
            score += (s32)SVM_W[c][i] * (s32)feats[i];
        if (score > best_score) {
            best_score = score;
            best_class = c + 1;
        }
    }
    return best_class;
}

