
/* =============================================================================
 * nir_baremetal.c  —  NIR Preprocessing Accelerator, Bare-metal PS demo
 * Zybo Z7-10, Vitis/SDK, standalone BSP
 *
 * WHAT THIS DOES:
 *   1. Embeds 5 test spectra (one per plastic class) as hardcoded arrays
 *   2. Writes each spectrum into in_bram via AXI BRAM Controller
 *   3. Pulses ctrl_start via AXI GPIO
 *   4. Polls ctrl_done
 *   5. Reads 224 INT8 features from out_bram
 *   6. Runs LinearSVC inference directly on ARM (integer Q15 dot product)
 *   7. Prints result to UART (115200 baud) — visible in PuTTY
 *   8. Drives LEDs to show result class (binary on LED[3:0])
 *
 * MEMORY MAP (match your Vivado Address Editor):
 *   IN_BRAM_BASE   0x40000000   AXI BRAM Controller 0
 *   OUT_BRAM_BASE  0x40002000   AXI BRAM Controller 1
 *   GPIO_BASE      0x41200000   AXI GPIO 0
 *
 * UART: PS UART0 or UART1 — Vitis BSP handles this via xil_printf
 *
 * HOW TO BUILD:
 *   Vitis → New Application Project
 *   Platform: from your exported .xsa
 *   Template: Empty Application (C)
 *   Paste this file as main.c
 *   Build → Run (JTAG)
 * =============================================================================
 */

